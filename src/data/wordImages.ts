/** واژه‌هایی که ایموجی یونیکد ندارند */
const LEGACY_ART_MAP: Record<string, string> = {
  'انار': 'anar', 'انجیر': 'anjir', 'داس': 'daas', 'قفس': 'ghafas', 'حوله': 'hoole', 'قیف': 'ghif',
};

const normEmoji = (e?: string) => (e ? e.trim().replace(/\uFE0F/g, '') : '');

export interface ResolvedVisual {
  src: string;
  kind: 'art' | 'emoji3d';
}

export const resolveWordVisual = (word?: string, emoji?: string): ResolvedVisual | undefined => {
  if (word) {
    const p = plainWord(word);
    const w3d = WORD_3D_MAP[p];
    if (w3d) return { src: `${EMOJI_BASE}${w3d}.webp`, kind: 'emoji3d' };
    const art = LEGACY_ART_MAP[p];
    if (art) return { src: `${WORDS_BASE}${art}.webp`, kind: 'art' };
  }
  const eKey = EMOJI_MAP[normEmoji(emoji)];
  if (eKey) return { src: `${EMOJI_BASE}${eKey}.webp`, kind: 'emoji3d' };
  return undefined;
};

export const wordImage = (word?: string, emoji?: string): string | undefined =>
  resolveWordVisual(word, emoji)?.src;

/** آیا برای این واژه/ایموجی تصویری (سه‌بعدی یا ایموجی واقعی) داریم؟ نماد جایگزین «__paper__» و 📖 حساب نمی‌شود. */
export const hasWordVisual = (word?: string, emoji?: string): boolean =>
  !!resolveWordVisual(word, emoji) || hasRealEmoji(emoji);
